const fs = require('node:fs')
const { parse, compileScript, compileTemplate } = require('E:/Code/Projects/Tian-AI-Agent-main/tian-ai-agent-frontend/node_modules/@vue/compiler-sfc')
const source = fs.readFileSync(__dirname + '/WikiPanel.vue', 'utf8')
const { descriptor, errors } = parse(source, { filename: 'WikiPanel.vue' })
if (errors.length) throw new Error(errors.join('\n'))
const script = compileScript(descriptor, { id: 'wiki' })
const template = compileTemplate({ source: descriptor.template.content, filename: 'WikiPanel.vue', id: 'wiki', compilerOptions: { bindingMetadata: script.bindings } })
if (template.errors.length) throw new Error(template.errors.join('\n'))
console.log('WikiPanel Markdown renderer: script and template compiled')
